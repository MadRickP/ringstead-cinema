-- Ringstead Cinema live seat reservations
-- Run this in the Supabase SQL editor after creating a project.

create table if not exists public.screenings (
  id text primary key,
  film_title text not null,
  screening_date date not null,
  start_time time not null,
  ticket_price numeric(8,2) not null default 5.00,
  capacity integer not null default 35
);

insert into public.screenings(id,film_title,screening_date,start_time,ticket_price,capacity)
values ('holy-days-2026-11-06','Holy Days','2026-11-06','19:30',5.00,35)
on conflict (id) do nothing;

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  screening_id text not null references public.screenings(id),
  seat_id text not null,
  name text not null,
  email text not null,
  phone text not null,
  created_at timestamptz not null default now(),
  unique(screening_id,seat_id)
);

alter table public.screenings enable row level security;
alter table public.reservations enable row level security;

-- Public availability function exposes ONLY seat IDs, never names/contact details.
create or replace function public.get_reserved_seats(p_screening_id text)
returns table(seat_id text)
language sql
security definer
set search_path = public
as $$ select r.seat_id from public.reservations r where r.screening_id=p_screening_id order by r.seat_id $$;

grant execute on function public.get_reserved_seats(text) to anon, authenticated;

-- Atomic reservation function. If any requested seat is already taken, no seats are reserved.
create or replace function public.reserve_seats(
  p_screening_id text,
  p_seat_ids text[],
  p_name text,
  p_email text,
  p_phone text
) returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  requested integer := coalesce(array_length(p_seat_ids,1),0);
  valid integer;
  taken text[];
  s text;
  reservation_id bigint;
begin
  if requested < 1 or requested > 8 then return json_build_object('success',false,'message','Please choose between 1 and 8 seats.'); end if;
  if p_name is null or length(trim(p_name)) < 2 then return json_build_object('success',false,'message','Please enter your name.'); end if;
  if p_email is null or position('@' in p_email) < 2 then return json_build_object('success',false,'message','Please enter a valid email address.'); end if;
  if exists(select 1 from unnest(p_seat_ids) x where x !~ '^[A-E][1-7]$') then return json_build_object('success',false,'message','Invalid seat selection.'); end if;
  select count(*) into valid from unnest(p_seat_ids); -- array uniqueness is enforced below
  if valid <> (select count(distinct x) from unnest(p_seat_ids) x) then return json_build_object('success',false,'message','A seat was selected more than once.'); end if;
  select array_agg(r.seat_id order by r.seat_id) into taken from public.reservations r where r.screening_id=p_screening_id and r.seat_id=any(p_seat_ids);
  if taken is not null then return json_build_object('success',false,'message','One or more of those seats has just been reserved. Please choose again.','taken',taken); end if;
  foreach s in array p_seat_ids loop
    insert into public.reservations(screening_id,seat_id,name,email,phone) values(p_screening_id,s,trim(p_name),trim(p_email),trim(p_phone)) returning id into reservation_id;
  end loop;
  return json_build_object('success',true,'message','Reservation confirmed.','seats',p_seat_ids);
exception when unique_violation then
  return json_build_object('success',false,'message','One or more of those seats has just been reserved. Please choose again.');
end;
$$;

grant execute on function public.reserve_seats(text,text[],text,text,text) to anon, authenticated;
